#!/usr/bin/env python3
"""Deterministic benchmark-corpus generator for the Lindblad vs Qiskit/Aer
comparison suite (R.1.14).

Emits, into benchmarks/compare/circuits/:
  - *.qasm                  gate-only OpenQASM 2.0 circuits (no creg, no
                            measure, exactly ONE qreg named q). Each harness
                            appends its own full-register terminal measurement
                            where sampling is benchmarked, so both engines
                            execute byte-identical gate content.
  - obs_heisenberg_n*.txt   shared observables: one term per line,
                            "<coeff> <pauli>" with the Pauli string in
                            LINDBLAD ORDER (index q acts on qubit q, LSB
                            first). The Qiskit harness reverses each string
                            to obtain the MSB-first Qiskit label.
  - coupling_*.edges        undirected edge lists: '#' comments, then one
                            line with the qubit count, then "u v" pairs.
                            Consumers symmetrise (add both directions).

Everything is seeded per workload via crc32(tag), and only
random.Random.random() is consumed (its sequence is stable across CPython
versions), so regeneration is reproducible. The corpus is COMMITTED anyway;
the seeds are belt and braces.

Run: python3 gen_circuits.py
"""

import math
import os
import random
import zlib

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "circuits")

# Workload size lists. The union of every consumer's needs; each harness picks
# its own subset (see bench_compare_*.cpp and aer_bench.py). n=8 / n=6 members
# exist for the cross-engine result-parity validation set.
SCALING_SIZES = [8, 10, 14, 16, 18, 22, 24, 26, 32, 40]   # SV: <=26, MPS: 16..40
DM_SIZES = [4, 6, 8, 10]
# 25/27-qubit members exist for the transpiler domain: circuits are sized TO
# the coupling maps (grid25 / linear27 / heavyhex27) because routing circuits
# SMALLER than the map currently trips a SABRE frozen-slot defect (see
# local/plans/TODO.md "Transpiler"); simulator domains do not use them.
QFT_SIZES = [8, 10, 14, 18, 22, 25, 27]
QV_SIZES = [8, 10, 14, 18, 22, 25, 27]
GROVER_SIZES = [8, 10, 12]        # search-register width s; total qubits 2s-3
CLIFFORD_SIZES = [8, 20, 40, 80, 160]
ANSATZ_SIZES = [8, 12, 16, 20]
OBSERVABLE_SIZES = [8, 12, 16, 20]

SCALING_LAYERS = 3
DM_LAYERS = 2
CLIFFORD_LAYERS = 10
ANSATZ_LAYERS = 3


def rng_for(tag):
    """Independent, version-stable stream per workload."""
    return random.Random(zlib.crc32(tag.encode("utf-8")))


def header(n, comment):
    return [
        "// " + comment,
        "// generated by benchmarks/compare/gen_circuits.py -- do not edit",
        "OPENQASM 2.0;",
        'include "qelib1.inc";',
        "qreg q[%d];" % n,
    ]


def write_qasm(name, lines):
    path = os.path.join(OUT_DIR, name)
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return path


def fisher_yates(seq, rng):
    """In-place shuffle using only rng.random() (stable across versions)."""
    for i in range(len(seq) - 1, 0, -1):
        j = int(rng.random() * (i + 1))
        seq[i], seq[j] = seq[j], seq[i]
    return seq


# =============================================================================
# Workload emitters
# =============================================================================

def gen_scaling(n, layers, name):
    """H layer + CX ladder + RZ layer, repeated. Mirrors the layered circuit
    used by benchmarks/bench_scaling.cpp so numbers stay comparable."""
    lines = header(n, "layered scaling circuit: %d qubits, %d layers" % (n, layers))
    for _ in range(layers):
        for i in range(n):
            lines.append("h q[%d];" % i)
        for i in range(n - 1):
            lines.append("cx q[%d],q[%d];" % (i, i + 1))
        for i in range(n):
            lines.append("rz(0.3) q[%d];" % i)
    write_qasm(name, lines)


def gen_qft(n):
    """Canonical LSB-LSB QFT: H + controlled-phase ladder + reversal swaps."""
    lines = header(n, "QFT circuit: %d qubits (with final swaps)" % n)
    for i in range(n):
        lines.append("h q[%d];" % i)
        for j in range(i + 1, n):
            angle = math.pi / (2 ** (j - i))
            lines.append("cp(%r) q[%d],q[%d];" % (angle, j, i))
    for i in range(n // 2):
        lines.append("swap q[%d],q[%d];" % (i, n - 1 - i))
    write_qasm("qft_n%d.qasm" % n, lines)


def gen_qv(n, depth):
    """Quantum-volume-style random circuit: per layer, a random qubit pairing;
    per pair, an SU(4)-approximating block (u3/cx/u3/cx/u3). Heavy on both
    1q fusion and 2q application, the standard cross-simulator stress test."""
    rng = rng_for("qv_n%d" % n)

    def u3(q):
        th, ph, lam = (2.0 * math.pi * rng.random() for _ in range(3))
        return "u3(%r,%r,%r) q[%d];" % (th, ph, lam, q)

    lines = header(n, "QV-style random circuit: %d qubits, depth %d" % (n, depth))
    for _ in range(depth):
        perm = fisher_yates(list(range(n)), rng)
        for k in range(0, n - 1, 2):
            a, b = perm[k], perm[k + 1]
            lines.append(u3(a))
            lines.append(u3(b))
            lines.append("cx q[%d],q[%d];" % (a, b))
            lines.append(u3(a))
            lines.append(u3(b))
            lines.append("cx q[%d],q[%d];" % (a, b))
            lines.append(u3(a))
            lines.append(u3(b))
    write_qasm("qv_n%d.qasm" % n, lines)


def mcx_vchain(controls, ancillas, target):
    """k-control Toffoli ladder (k >= 3) with k-2 ancillas, compute/uncompute.
    Returns ccx lines. Ancillas are returned to |0>."""
    k = len(controls)
    assert k >= 3 and len(ancillas) >= k - 2
    fwd = ["ccx q[%d],q[%d],q[%d];" % (controls[0], controls[1], ancillas[0])]
    for i in range(2, k - 1):
        fwd.append("ccx q[%d],q[%d],q[%d];" % (controls[i], ancillas[i - 2], ancillas[i - 1]))
    lines = list(fwd)
    lines.append("ccx q[%d],q[%d],q[%d];" % (controls[k - 1], ancillas[k - 3], target))
    lines.extend(reversed(fwd))
    return lines


def gen_grover(s):
    """Grover search over s qubits for a NON-SYMMETRIC marked state
    (bit i = 0 iff i % 3 == 1), so the run doubles as a cross-engine qubit-
    ordering convention check (a symmetric target would mask ordering bugs;
    see CLAUDE.md). Multi-controlled Z is lowered to a ccx v-chain over s-3
    ancilla qubits: total register = 2s-3, single qreg (the Lindblad QASM2
    parser maps bracket indices of one register). Ancillas end in |0>."""
    n = 2 * s - 3
    marked = [0 if i % 3 == 1 else 1 for i in range(s)]
    iters = int(math.floor(math.pi / 4.0 * math.sqrt(2.0 ** s)))
    controls = list(range(s - 1))
    ancillas = list(range(s, n))
    target = s - 1

    def mcz():
        out = ["h q[%d];" % target]
        out += mcx_vchain(controls, ancillas, target)
        out.append("h q[%d];" % target)
        return out

    lines = header(n, "Grover: %d search qubits + %d ancillas, %d iterations, "
                      "marked state bits(LSB-first) %s"
                      % (s, s - 3, iters, "".join(map(str, marked))))
    for i in range(s):
        lines.append("h q[%d];" % i)
    for _ in range(iters):
        # Oracle: phase-flip |marked> via X conjugation on the 0-bits + MCZ.
        zeros = [i for i in range(s) if marked[i] == 0]
        for i in zeros:
            lines.append("x q[%d];" % i)
        lines += mcz()
        for i in zeros:
            lines.append("x q[%d];" % i)
        # Diffusion about the mean.
        for i in range(s):
            lines.append("h q[%d];" % i)
        for i in range(s):
            lines.append("x q[%d];" % i)
        lines += mcz()
        for i in range(s):
            lines.append("x q[%d];" % i)
        for i in range(s):
            lines.append("h q[%d];" % i)
    write_qasm("grover_n%d.qasm" % s, lines)


def gen_clifford(n, layers):
    """H + CX ladder + S layers: stabilizer-simulable on both engines."""
    lines = header(n, "Clifford circuit: %d qubits, %d layers" % (n, layers))
    for _ in range(layers):
        for i in range(n):
            lines.append("h q[%d];" % i)
        for i in range(n - 1):
            lines.append("cx q[%d],q[%d];" % (i, i + 1))
        for i in range(n):
            lines.append("s q[%d];" % i)
    write_qasm("clifford_n%d.qasm" % n, lines)


def gen_ansatz(n, layers):
    """Hardware-efficient ansatz with baked-in deterministic angles and NO
    measurements (estimator workloads must be measure-free: Lindblad's
    Estimator throws on measure at shots == 0 by frozen convention)."""
    rng = rng_for("ansatz_n%d" % n)
    lines = header(n, "hardware-efficient ansatz: %d qubits, %d layers, no measure"
                      % (n, layers))
    for _ in range(layers):
        for i in range(n):
            lines.append("ry(%r) q[%d];" % (2.0 * math.pi * rng.random(), i))
        for i in range(n):
            lines.append("rz(%r) q[%d];" % (2.0 * math.pi * rng.random(), i))
        for i in range(n - 1):
            lines.append("cx q[%d],q[%d];" % (i, i + 1))
    write_qasm("ansatz_n%d.qasm" % n, lines)


def gen_observable(n):
    """1D Heisenberg chain: sum_i (XX + YY + ZZ)_{i,i+1} + 0.5 * sum_i Z_i.
    Pauli strings are written in LINDBLAD order (index q = qubit q)."""
    def term(paulis):  # paulis = {qubit: 'X'|'Y'|'Z'}
        s = ["I"] * n
        for q, p in paulis.items():
            s[q] = p
        return "".join(s)

    lines = ["# obs_heisenberg_n%d.txt -- '<coeff> <pauli>' per line," % n,
             "# pauli string in LINDBLAD order: char q acts on qubit q (LSB first).",
             "# The Qiskit harness must REVERSE the string for a Qiskit label."]
    for i in range(n - 1):
        for p in ("X", "Y", "Z"):
            lines.append("1.0 %s" % term({i: p, i + 1: p}))
    for i in range(n):
        lines.append("0.5 %s" % term({i: "Z"}))
    with open(os.path.join(OUT_DIR, "obs_heisenberg_n%d.txt" % n), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


# =============================================================================
# Coupling maps (shared edge lists so BOTH engines route on identical graphs)
# =============================================================================

# 27-qubit heavy-hex lattice (IBM Falcon layout, e.g. ibmq_mumbai).
HEAVY_HEX_27 = [
    (0, 1), (1, 2), (1, 4), (2, 3), (3, 5), (4, 7), (5, 8), (6, 7), (7, 10),
    (8, 9), (8, 11), (10, 12), (11, 14), (12, 13), (12, 15), (13, 14),
    (14, 16), (15, 18), (16, 19), (17, 18), (18, 21), (19, 20), (19, 22),
    (21, 23), (22, 25), (23, 24), (24, 25), (25, 26),
]


def gen_couplings():
    def write_edges(name, n, edges, desc):
        lines = ["# %s -- %s" % (name, desc),
                 "# first non-comment line: qubit count; then undirected 'u v' pairs.",
                 "# consumers symmetrise (add both directions).",
                 str(n)]
        lines += ["%d %d" % (u, v) for u, v in edges]
        with open(os.path.join(OUT_DIR, name), "w", newline="\n") as f:
            f.write("\n".join(lines) + "\n")

    write_edges("coupling_linear27.edges", 27,
                [(i, i + 1) for i in range(26)], "27-qubit line")
    grid = []
    for r in range(5):
        for c in range(5):
            i = 5 * r + c
            if c < 4:
                grid.append((i, i + 1))
            if r < 4:
                grid.append((i, i + 5))
    write_edges("coupling_grid25.edges", 25, grid, "5x5 grid")
    write_edges("coupling_heavyhex27.edges", 27, HEAVY_HEX_27,
                "27-qubit heavy-hex (IBM Falcon layout)")


# =============================================================================
# Main
# =============================================================================

def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    for n in SCALING_SIZES:
        gen_scaling(n, SCALING_LAYERS, "scaling_n%d.qasm" % n)
    for n in DM_SIZES:
        gen_scaling(n, DM_LAYERS, "dmscaling_n%d.qasm" % n)
    for n in QFT_SIZES:
        gen_qft(n)
    for n in QV_SIZES:
        gen_qv(n, depth=n)
    for s in GROVER_SIZES:
        gen_grover(s)
    for n in CLIFFORD_SIZES:
        gen_clifford(n, CLIFFORD_LAYERS)
    for n in ANSATZ_SIZES:
        gen_ansatz(n, ANSATZ_LAYERS)
    for n in OBSERVABLE_SIZES:
        gen_observable(n)
    gen_couplings()
    count = len(os.listdir(OUT_DIR))
    print("wrote %d files to %s" % (count, OUT_DIR))


if __name__ == "__main__":
    main()
