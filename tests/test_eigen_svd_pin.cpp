TEST(EigenSvdPin, TheFrozenSimon36MatchesItsDocumentedStructure) {
    // A literal is only a reproducer while it is the matrix it claims to be, and
    // nothing else in the tree would notice an editing accident in 1296 hex
    // floats. The structure is stated in the header: real throughout, entries at
    // magnitude 1/6 in a sparse pattern, plus one residue term left by the peel.
    const auto M = simon36_r1112::build_simon36_r1112();
    ASSERT_EQ(M.rows(), 36);
    ASSERT_EQ(M.cols(), 36);

    const double sixth = 1.0 / 6.0;
    int at_sixth = 0;
    double max_imag = 0.0;
    double max_other = 0.0;
    for (Eigen::Index c = 0; c < M.cols(); ++c) {
        for (Eigen::Index r = 0; r < M.rows(); ++r) {
            const double re = std::abs(M(r, c).real());
            max_imag = std::max(max_imag, std::abs(M(r, c).imag()));
            if (std::abs(re - sixth) <= 64.0 * kEps) ++at_sixth;
            else max_other = std::max(max_other, re);
        }
    }

    EXPECT_EQ(max_imag, 0.0)
        << "the frozen matrix is real; a nonzero imaginary part means the "
           "literal was edited or re-emitted from a different state";
    EXPECT_EQ(at_sixth, 3 * simon36_rank())
        << "expected three entries of magnitude 1/6 per retained direction";
    EXPECT_LT(max_other, 1e-15)
        << "every entry that is not 1/6 should be peel residue near zero, but "
           "one reached " << max_other;
    EXPECT_NEAR(M.squaredNorm(), 1.0, backward_tol(36, 1.0))
        << "the block is the residual of a normalised state, so its Frobenius "
           "norm is 1 by construction";
}

