// test_eigen_svd_pin.cpp - does the pinned Eigen factorise our two reproducers
// correctly, and does the library path over the same inputs still hold?
//
// Those are two questions, and this file keeps them in two suites, because a
// failure means something different in each and mixing them makes neither
// answerable.
//
//   EigenSvdPin      the DEPENDENCY. Every input is a hex-float literal, so a
//                    failure is attributable to the pinned Eigen and to nothing
//                    else. This is the suite that makes a pin change
//                    self-reporting: bump the pin, run this, read the result.
//
//   LibrarySvdPath   the END-TO-END path. Every input is built by evolving a
//                    circuit through this library, so a failure may belong to
//                    either side. Still worth having, since it is the only
//                    thing that notices when our own construction of these
//                    matrices drifts, but it cannot be read as a verdict on
//                    Eigen.
//
// The distinction is not academic. build_poison_theta() evolves a Shor prefix
// through MPSSimulator and hand-applies the remaining instructions, and
// build_bdcsvd_bug_matrix() evolves a QuditStatevector through a QFT and an
// oracle. Both therefore pass through the code they are meant to be testing,
// and both drift whenever the MPS layer changes. The frozen literals do not.
//
// The other suites over these matrices assert the LADDER's contract: that the
// kept slice is clean and reconstructs, whatever the backend hands it. That is
// the right question for the library and the wrong one for the dependency,
// because the hardening answers it green on a defective Eigen and a healthy one
// alike. Confirmed directly: running three Eigen versions against those suites
// passed 24 of 24 every time, on a version carrying a real defect and on ones
// that do not.
//
// The two reproducers:
//
//   the 36x36, rank 12, twelve-fold degenerate. Eigen 3.4.0's BDCSVD violates
//     the Frobenius identity on it, emitting a singular value belonging to no
//     true spectrum while every entry stays finite. JacobiSVD is correct on the
//     same input. Fixed upstream in 3.4.1.
//
//   the 8x8, spectrum {1,1,1,1,0,0,0,0}. JacobiSVD returns NaN inside a
//     null-space column of U while S, V and the leading rank-4 slice stay exact
//     (issue #44). That failure is a -ffast-math artifact rather than an Eigen
//     defect: the flag folds away the finiteness guard JacobiSVD writes at its
//     own entry, and under strict floating point every Eigen version tested
//     factorises it correctly.
//
// Which is why nothing here carries a per-file floating-point flag. It could
// not deliver one: Eigen's instantiations have vague linkage and the linker
// keeps one per binary regardless of which unit's flags produced it. Strictness
// comes from the factorisation running inside src/eigen_backend.cpp, the tree's
// only emitter, which is compiled strict unconditionally and which
// test_v11241_seam_rules.cpp keeps sole.
//
// The null-space NaN is why these assertions read the FULL factorisation
// through SvdReport::corrupt and the bad-column lists. A kept-slice check
// cannot see it: the damage sits in columns a truncation discards, which is
// exactly why the library survives it and why a pin test must not.

