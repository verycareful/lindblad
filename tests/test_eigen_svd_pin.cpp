constexpr double kEps = std::numeric_limits<double>::epsilon();

// Slack a backward-stable SVD is entitled to, in units of N*eps*||M||_F. The
// same figure svd_truncate's VERIFY rung allows, so this suite and the ladder
// agree on what "correct" means and cannot disagree about a given Eigen.
constexpr double kBackwardErrorSlack = 64.0;

double backward_tol(int n, double frob_sq) {
    return kBackwardErrorSlack * static_cast<double>(n) * kEps *
           std::sqrt(frob_sq);
}

// Rank of the Simon residual block, derived rather than transcribed: f is
// constant on the cosets of the subgroup generated by the hidden period, so it
// takes d^n / |<s>| distinct values, and the block carries one direction per
// distinct output.
int simon_distinct_outputs(int d, const std::vector<int>& s) {
    std::set<std::vector<int>> subgroup;
    for (int k = 0; k < d; ++k) {
        std::vector<int> e;
        e.reserve(s.size());
        for (int c : s) e.push_back((k * c) % d);
        subgroup.insert(e);
    }
    int total = 1;
    for (size_t i = 0; i < s.size(); ++i) total *= d;
    return total / static_cast<int>(subgroup.size());
}

// Assert a factorisation is one a correct SVD could have produced. Checks the
// whole of U, S and V, not the retained slice.
void expect_healthy(const char* tag, const SvdReport& r, int n, int expect_rank,
                    double expect_sigma) {
    print_svd_report_line(std::cout, tag, r);

    // Non-finite anywhere in the factorisation, INCLUDING the null-space
    // columns a truncation would discard.
    EXPECT_FALSE(r.s_bad) << tag << ": non-finite singular value";
    EXPECT_TRUE(r.u_bad_cols.empty())
        << tag << ": " << r.u_bad_cols.size() << " column(s) of U hold "
        << "non-finite entries, first at " << r.u_bad_cols.front();
    EXPECT_TRUE(r.v_bad_cols.empty())
        << tag << ": " << r.v_bad_cols.size() << " column(s) of V hold "
        << "non-finite entries, first at " << r.v_bad_cols.front();
    ASSERT_FALSE(r.corrupt) << tag << ": factorisation corrupt, nothing below "
                            << "this point is measurable";

    // Frobenius identity. An SVD preserves the norm exactly, so a violation is
    // a wrong spectrum rather than an imprecise one. This is the check that
    // catches the 36x36 defect, whose output is entirely finite and therefore
    // invisible to every scan above.
    EXPECT_NEAR(r.sum_sq, r.frob_sq, backward_tol(n, r.frob_sq) * r.frob_sq)
        << tag << ": sum of sigma^2 is " << r.sum_sq << " against ||M||_F^2 "
        << r.frob_sq;

    EXPECT_EQ(r.rank, expect_rank) << tag << ": retained rank";

    EXPECT_LT(r.recon_err, backward_tol(n, r.frob_sq))
        << tag << ": U S V^H does not reconstruct M";

    // Every significant sigma sits on the degenerate value. A spurious entry
    // displacing a real one shows up here even when the norm happens to close.
    for (int i = 0; i < expect_rank && i < static_cast<int>(r.top.size()); ++i) {
        EXPECT_NEAR(r.top[static_cast<size_t>(i)], expect_sigma,
                    backward_tol(n, r.frob_sq))
            << tag << ": sigma[" << i << "] is off the degenerate value";
    }
}

// The 36x36 is the residual of a normalised state, so ||M||_F^2 == 1 and the
// rank equal sigmas each carry 1/rank of the weight.
int simon36_rank() { return simon_distinct_outputs(6, {2, 4}); }
double simon36_sigma() {
    return std::sqrt(1.0 / static_cast<double>(simon36_rank()));
}

// The 8x8: four orthonormal directions survive the gate, so the spectrum is
// four equal values over a four-dimensional null space. The frozen literal
// holds them at one each, so its ||M||_F^2 == 4.
constexpr int kPoisonRank = 4;
constexpr double kPoisonSigma = 1.0;

// The built block is the canonical block at that point in the run, which
// carries the state's unit norm: the four equal values share a weight of 1,
// so each is 1/sqrt(4).
double built_poison_sigma() {
    return std::sqrt(1.0 / static_cast<double>(kPoisonRank));
}

